#!/usr/bin/env node
// ═══════════════════════════════════════════════
// 🛡️ يولّد docs/terboo-permission-matrix.json (F) من محرّك الصلاحيات نفسه + جرد الأوامر
//   node tools/terboo-permission-matrix.mjs
// ═══════════════════════════════════════════════

import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const { LEVEL, LEGACY_ROLE_CATEGORIES, permissionMatrix } = await import("../src/lib/terboo-permissions.js");
const plugins = JSON.parse(fs.readFileSync(path.join(ROOT, "docs/inventory/after/plugins.json"), "utf8"));
const commands = plugins.filter((p) => p.registered).map((p) => ({
  command: p.name,
  path: p.path,
  category: p.category,
  enforcedBy: p.permissions.owner ? "registry: owner"
    : LEGACY_ROLE_CATEGORIES.has(p.category) ? "plugin legacy roles (cPanel owner/ceo/reseller · DigitalOcean sellers) + hidden from AI without role"
    : p.permissions.admin ? "registry: group admin" : p.permissions.premium ? "registry: premium" : "registry: public",
  ...p.permissions,
}));
const out = {
  $comment: "Generated by tools/terboo-permission-matrix.mjs from src/lib/terboo-permissions.js and docs/inventory/after — do not edit by hand.",
  model: "Identity (PN/LID ⇒ canonical) at execution time → level (owner · group-admin · panel-owner · vps-buyer · user) → action policy → decision (allowed · denied · needs-confirmation · needs-target · needs-owner · resource-not-owned · provider-not-available) → plugin re-checks before executing.",
  levels: Object.values(LEVEL),
  actions: permissionMatrix(),
  commands,
  summary: {
    actions: permissionMatrix().length,
    commands: commands.length,
    ownerCommands: commands.filter((c) => c.owner).length,
    adminCommands: commands.filter((c) => c.admin).length,
    premiumCommands: commands.filter((c) => c.premium).length,
    legacyRoleCommands: commands.filter((c) => c.enforcedBy.startsWith("plugin legacy roles")).length,
  },
};
fs.writeFileSync(path.join(ROOT, "docs", "terboo-permission-matrix.json"), `${JSON.stringify(out, null, 2)}\n`);
console.log(`✅ docs/terboo-permission-matrix.json: ${JSON.stringify(out.summary)}`);
process.exit(0);
