import fs from "node:fs";
import path from "node:path";
import { registrySnapshot, searchTools } from "../src/lib/terboo-tool-registry.js";

const snapshot = registrySnapshot();
const out = {
  $comment: "Generated by tools/terboo-tool-registry.mjs from src/lib/terboo-tool-registry.js — do not edit by hand.",
  generatedAt: new Date().toISOString(),
  total: snapshot.total,
  scrapers: snapshot.scrapers,
  mediaTools: snapshot.mediaTools,
  categories: snapshot.categories,
  toolSearch: {
    rule: "The model never receives all tools: buildInstruction() lists only the top matches of searchTools(request, context), limit 10; owner-only tools are hidden from non-owners; tools with an open circuit are demoted.",
    examples: Object.fromEntries([
      ["حمل الفيديو ده https://vt.tiktok.com/ZSabc123/", {}],
      ["ابحث عن ايفون 15 في جوجل", {}],
      ["شيل الخلفية", { hasImage: true }],
      ["فرغ التسجيل", { hasAudio: true }],
      ["لخص الملف", { hasDocument: true }],
    ].map(([query, ctx]) => [query, searchTools(query, { ...ctx, limit: 3 }).map((x) => x.id)])),
  },
  tools: snapshot.tools.map((tool) => ({
    id: tool.id, category: tool.category, source: tool.source, target: tool.target, kind: tool.kind, purpose: tool.purpose,
    platforms: tool.platforms, input: tool.input, output: tool.output, permission: tool.permission, auth: tool.auth, safety: tool.safety,
    timeoutMs: tool.timeoutMs, maxBytes: tool.maxBytes || undefined, maxChars: tool.maxChars || undefined,
    retries: tool.retries, maxAttempts: tool.maxAttempts, fallbacks: tool.fallbacks, modelVisible: tool.modelVisible, alias: tool.alias || undefined,
  })),
};
const file = path.join(process.cwd(), "docs", "terboo-tool-registry.json");
fs.mkdirSync(path.dirname(file), { recursive: true });
fs.writeFileSync(file, `${JSON.stringify(out, null, 2)}\n`);
console.log(`✅ ${path.relative(process.cwd(), file)}: ${out.total} أداة (${out.scrapers} scraper · ${out.mediaTools} وسائط) · ${Object.keys(out.categories).length} فئة`);
