#!/usr/bin/env node
// ═══════════════════════════════════════════════
// 🎛️ يولّد docs/terboo-command-ui-matrix.json من محرك قدرات الواجهة (مصدر واحد للحقيقة)
//   node tools/terboo-command-ui-matrix.mjs          ⇒ يكتب الملف
//   node tools/terboo-command-ui-matrix.mjs --check  ⇒ يفشل إن كان الملف قديماً
// لكل أمر حيّ: هل الزر مناسب؟ نوعه · المعاملات · الصلاحية · الهدف · مدمّر؟ · نص حر؟ · الرد المتوقع.
// ═══════════════════════════════════════════════

import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const tmpDb = fs.mkdtempSync(path.join(os.tmpdir(), "terboo-ui-matrix-"));
const { initDatabase } = await import("../src/lib/terboo-database.js");
await initDatabase(tmpDb);
const { loadPlugins } = await import("../src/lib/terboo-plugins.js");
await loadPlugins(path.join(process.cwd(), "plugins"));
const { uiMatrix } = await import("../src/lib/terboo-command-ui.js");

const commands = uiMatrix().sort((a, b) => a.category.localeCompare(b.category) || a.command.localeCompare(b.command));
const count = (fn) => commands.filter(fn).length;
const out = {
  $comment: "Generated by tools/terboo-command-ui-matrix.mjs from src/lib/terboo-command-ui.js (derived from each plugin's usage/permissions, overridable by config.ui) — do not edit by hand.",
  rules: {
    button: "a defined action whose inputs are known, no free text, known target, deterministic",
    noButton: "free-form text, a URL not given, a file/media, code, an arbitrary target, several unknown values",
    destructive: "never a direct button: action → confirmation → execute (confirm-after-target when a target is needed)",
    ai: "the model proposes responseMode (text|buttons|confirm); resolveResponseMode decides; no button for a command the viewer cannot run",
  },
  summary: {
    commands: commands.length,
    quickReply: count((c) => c.buttonType === "quick-reply"),
    select: count((c) => c.buttonType === "select"),
    confirm: count((c) => c.buttonType === "confirm"),
    afterTarget: count((c) => c.buttonType === "after-target-resolution"),
    none: count((c) => c.buttonType === "none"),
    destructive: count((c) => c.destructive),
    freeForm: count((c) => c.freeForm),
    needsTarget: count((c) => c.target),
    needsMedia: count((c) => c.ui.requiresMedia || c.ui.requiresReply),
    declared: count((c) => c.ui.source === "declared"),
  },
  commands,
};

const file = path.join(process.cwd(), "docs", "terboo-command-ui-matrix.json");
const text = `${JSON.stringify(out, null, 2)}\n`;
fs.rmSync(tmpDb, { recursive: true, force: true });
if (process.argv.includes("--check")) {
  const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
  if (current !== text) {
    console.error(`❌ ${path.relative(process.cwd(), file)} قديم — شغّل: node tools/terboo-command-ui-matrix.mjs`);
    process.exit(1);
  }
  console.log(`✅ ${path.relative(process.cwd(), file)} مطابق (${commands.length} أمر)`);
  process.exit(0);
}
fs.writeFileSync(file, text);
console.log(`✅ ${path.relative(process.cwd(), file)}: ${commands.length} commands · ${JSON.stringify(out.summary)}`);
process.exit(0);
