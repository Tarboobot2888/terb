#!/usr/bin/env node
// ═══════════════════════════════════════════════
// 👁️ يولّد docs/terboo-visual-matrix.json من Visual Command Eligibility Engine
//   node tools/terboo-visual-matrix.mjs          ⇒ يكتب الملف ويطبع الملخّص
//   node tools/terboo-visual-matrix.mjs --check  ⇒ يفشل إن كان الملف قديماً
// لكل أمر حيّ: الشكل المستحق (html/hybrid/buttons/media/text) · ما يُسلَّم فعلاً · أسباب القرار.
// ═══════════════════════════════════════════════

import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const tmpDb = fs.mkdtempSync(path.join(os.tmpdir(), "terboo-visual-matrix-"));
const { initDatabase } = await import("../src/lib/terboo-database.js");
await initDatabase(tmpDb);
const { loadPlugins } = await import("../src/lib/terboo-plugins.js");
await loadPlugins(path.join(process.cwd(), "plugins"));
const { visualMatrix } = await import("../src/lib/terboo-visual-response.js");

const rows = visualMatrix();
const tally = (key) => rows.reduce((acc, r) => ({ ...acc, [r[key]]: (acc[r[key]] || 0) + 1 }), {});
const out = {
  $comment: "Generated by tools/terboo-visual-matrix.mjs from src/lib/terboo-visual-response.js — do not edit by hand.",
  rule: "Unified TERBOO ARCADE rooms emit a 3D HTML view plus native WhatsApp controls/text fallback; the in-card HTML action bridge remains unproven, and board images are no longer generated.",
  summary: { commands: rows.length, eligible: tally("mode"), delivered: tally("delivered"), htmlEligible: rows.filter((r) => r.htmlEligible).length },
  commands: rows,
};
const file = path.join(process.cwd(), "docs", "terboo-visual-matrix.json");
const text = `${JSON.stringify(out, null, 1)}\n`;
if (process.argv.includes("--check")) {
  const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
  if (current !== text) {
    console.error("❌ docs/terboo-visual-matrix.json قديم — شغّل node tools/terboo-visual-matrix.mjs");
    process.exit(1);
  }
} else fs.writeFileSync(file, text);
console.log(JSON.stringify(out.summary));
process.exit(0);
